from datetime import datetime
from zoneinfo import ZoneInfo


def dated_prompt(prompt: str) -> str:
    today = datetime.now(ZoneInfo("Asia/Shanghai")).date().isoformat()
    return f"{prompt}\n当前业务日期：{today}（Asia/Shanghai）。相对日期以此为准。"


